import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const schemaPath = path.join(root, "protocol", "v1.3.4", "room-protocol.schema.json");
const outputPath = path.join(root, "shared", "src", "generated", "room-protocol.ts");
const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const refName = (ref) => ref.split("/").at(-1);
const literal = (value) => JSON.stringify(value);
const toType = (node) => {
  if (node.$ref) return refName(node.$ref);
  if (node.const !== undefined) return literal(node.const);
  if (node.enum) return node.enum.map(literal).join(" | ");
  if (node.anyOf || node.oneOf) return (node.anyOf ?? node.oneOf).map(toType).join(" | ");
  if (Array.isArray(node.type)) return node.type.map((type) => toType({ ...node, type })).join(" | ");
  if (node.type === "array") return `Array<${toType(node.items ?? {})}>`;
  if (node.type === "object") {
    if (!node.properties && node.additionalProperties && typeof node.additionalProperties === "object") return `Record<string, ${toType(node.additionalProperties)}>`;
    const required = new Set(node.required ?? []);
    const fields = Object.entries(node.properties ?? {}).map(([key, value]) => `  ${JSON.stringify(key)}${required.has(key) ? "" : "?"}: ${toType(value)};`);
    if (node.additionalProperties === true) fields.push("  [key: string]: unknown;");
    return `{\n${fields.join("\n")}\n}`;
  }
  if (node.type === "string") return "string";
  if (node.type === "number" || node.type === "integer") return "number";
  if (node.type === "boolean") return "boolean";
  if (node.type === "null") return "null";
  return "unknown";
};
const definitions = Object.entries(schema.$defs).map(([name, definition]) => `export type ${name} = ${toType(definition)};`);
const output = ["// Generated by tools/build-room-protocol.mjs. Do not edit directly.", "// Source: protocol/v1.3.4/room-protocol.schema.json", "", ...definitions, "", `export type RoomProtocolMessage = ${schema.oneOf.map(toType).join(" | ")};`, ""].join("\n\n");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(JSON.stringify({ definitions: definitions.length, output: path.relative(root, outputPath) }, null, 2));
