export function describeCard(cardId: string): string {
  if (!cardId) return FALLBACK;
  const direct = cardMap[cardId];
  if (direct) return direct;
  const prefix = cardId.replace(/\.(white|green|blue|orange|red)$/, "");
  const byPrefix = cardMap[prefix];
  if (byPrefix) return byPrefix;
  const categoryPrefix = cardId.split(".").slice(0, 2).join(".");
  const byCategory = cardMap[categoryPrefix];
  if (byCategory) return byCategory;
  return FALLBACK;
}

// 卡片描述优先用服务端 summary；为空时回退本地配置。
export function cardSummary(cardId: string | undefined, serverSummary: string | undefined): string {
  if (serverSummary && serverSummary.trim()) return serverSummary;
  return cardId ? describeCard(cardId) : FALLBACK;
}
